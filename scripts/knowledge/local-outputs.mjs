import { readFile, lstat, mkdir, rename } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';
import { randomUUID } from 'node:crypto';
import { atomicWrite, jsonBytes } from './owner-transaction.mjs';
import { readJson } from './release-boundary.mjs';
const registry='knowledge/local-outputs.json';
const evidence='artifacts/oak-ai-agent-2026-10-03/knowledge-lifecycle/retired-outputs';
async function safeOutput(root,path) {
  const rel=relative(resolve(root),resolve(root,path));
  if(rel!=='dist'&&!/^artifacts\/oak-ai-agent-2026-10-03\/knowledge-parity\/public\/oak-[a-f0-9]{64}$/.test(rel)) throw new Error('Unsupported local public output destination');
  let cursor=resolve(root);
  for(const part of rel.split(sep)) {
    cursor=join(cursor,part);
    try {if((await lstat(cursor)).isSymbolicLink())throw new Error('Public output must not traverse a symlink');}
    catch(error){if(error.code==='ENOENT')break;throw error;}
  }
  return rel;
}
export async function registerLocalOutput(root,path,revision,generation) {
  const output=await safeOutput(root,path);
  let existing={schema:'oak.local-public-outputs.v1',outputs:[]};
  try{existing=await readJson(join(root,registry));}catch(error){if(error.code!=='ENOENT')throw error;}
  existing.outputs=existing.outputs.filter(item=>item.path!==output);
  existing.outputs.push({path:output,revision,generation});
  await atomicWrite(join(root,registry),jsonBytes(existing));
}
export async function retireLocalOutputs(root) {
  let existing={outputs:[]};
  try{existing=await readJson(join(root,registry));}catch(error){if(error.code!=='ENOENT')throw error;}
  // Also protect a pre-lifecycle dist generated by Astro's ordinary build.
  try{await lstat(join(root,'dist'));if(!existing.outputs.some(item=>item.path==='dist'))existing.outputs.push({path:'dist',revision:'pre-lifecycle'});}
  catch(error){if(error.code!=='ENOENT')throw error;}
  const retired=[];
  for(const item of existing.outputs) {
    const output=await safeOutput(root,item.path),target=`${evidence}/${randomUUID()}`;
    await mkdir(join(root,evidence),{recursive:true});
    try{await rename(join(root,output),join(root,target));retired.push({...item,privateAuditPath:target});}
    catch(error){if(error.code!=='ENOENT')throw error;}
  }
  await atomicWrite(join(root,registry),jsonBytes({schema:'oak.local-public-outputs.v1',outputs:[]}));
  return retired;
}
