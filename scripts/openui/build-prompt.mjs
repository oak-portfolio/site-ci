const CLAIMS = [null, "one", "pair", "list"];
const JUDGE_KINDS = ["walk", "walk-values", "heading", "claims", "numbered", "compare-row", "metric", "meter", "dated", "label", "pills", "proposal"];
const KEYS = ["name", "claims", "holds", "opensOnCard", "intro", "pendingKind", "pendingCap", "salvageContainer", "skeleton", "view",
  "planned", "plan", "structured", "structure", "judgeView", "taughtPresets"];

export function oakBlockFragments(from = fragmentDir) {
  return readdirSync(from).filter(file => file.endsWith(".json")).sort()
    .map(file => ({ file, ...JSON.parse(readFileSync(`${from}${file}`, "utf8")) }))
    .map(({ file, ...fragment }) => { if (`${fragment.name}.json` !== file) throw new Error(`openui: ${file} names ${fragment.name}`); return fragment; });
}

const isBool = value => typeof value === "boolean";
const isNames = value => Array.isArray(value) && value.every(item => typeof item === "string" && /^[A-Z]\w*$/.test(item));

export function oakBlockProblems(fragment) {
  const problems = [];
  const need = (ok, problem) => { if (!ok) problems.push(`${fragment.name ?? "?"}: ${problem}`); };
  need(typeof fragment.name === "string" && /^[A-Z]\w*$/.test(fragment.name), "name is a component name");
  need(Object.keys(fragment).every(key => KEYS.includes(key)), `only known keys (${KEYS.join(", ")})`);
  need(CLAIMS.includes(fragment.claims), "claims is null, one, pair or list");
  need(isNames(fragment.holds), "holds lists component names");
  need(isBool(fragment.opensOnCard), "opensOnCard is a boolean");
  need(fragment.intro === null || (fragment.intro && typeof fragment.intro === "object" &&
    (typeof fragment.intro.line === "string") !== (typeof fragment.intro.count === "string")), "intro is null, { line } or { count }");
  need(fragment.pendingKind === null || /^[a-z]+$/.test(fragment.pendingKind ?? ""), "pendingKind is null or a lowercase kind");
  need(fragment.pendingKind === null ? fragment.pendingCap === null : Number.isInteger(fragment.pendingCap) && fragment.pendingCap > 0,
    "pendingCap is a positive integer with a pendingKind, else null");
  need(isBool(fragment.salvageContainer), "salvageContainer is a boolean");
  need(fragment.skeleton === null || /^[a-z]+$/.test(fragment.skeleton ?? ""), "skeleton is null or a lowercase kind");
  need(fragment.view === null || (typeof fragment.view === "string" && /^views\/[a-z-]+\.ts$/.test(fragment.view) && existsSync(`${dir}${fragment.view}`)),
    "view is null or views/<name>.ts that exists");
  need("plan" in fragment ? !("planned" in fragment) : fragment.planned === false, "a plan field, or planned: false");
  const rule = "plan" in fragment ? oakPlanRuleSchema.safeParse(fragment.plan) : { success: true };
  need(rule.success, `plan is a plan rule (plan-rule.ts)${rule.error ? `: ${rule.error.issues.map(issue => `${issue.path.join(".") || "plan"} ${issue.message}`).join("; ")}` : ""}`);
  need(isBool(fragment.structured), "structured is an explicit boolean");
  need(isBool(fragment.structure), "structure is an explicit boolean");
  need(Boolean(fragment.judgeView) && JUDGE_KINDS.includes(fragment.judgeView.kind), `judgeView names a kind (${JUDGE_KINDS.join(", ")})`);
  need(Array.isArray(fragment.taughtPresets) && fragment.taughtPresets.every(item => typeof item === "string"), "taughtPresets lists preset names");
  return problems;
}

export function oakBlocksSource(fragments) {
  const ordered = fragments.map(fragment => Object.fromEntries(KEYS.filter(key => key in fragment).map(key => [key, fragment[key]])));
  const pending = ordered.filter(fragment => fragment.pendingKind).sort((a, b) => a.pendingKind.localeCompare(b.pendingKind));
  const kind = pending.map(fragment => JSON.stringify(fragment.pendingKind)).join(" | ") || "never";
  return [
    "// Generated by scripts/openui/build-prompt.mjs from components/*.json. Do not edit.",
    "",
    "export type OakOpenUIJudgeView = Readonly<{ kind: string; prop?: string; prefix?: string; text?: string }>;",
    "export type OakOpenUIBlock = Readonly<{",
    "  name: string; claims: 'one' | 'pair' | 'list' | null; holds: readonly string[]; opensOnCard: boolean;",
    "  intro: Readonly<{ line?: string; count?: string }> | null; pendingKind: OakPendingKind | null; pendingCap: number | null;",
    "  salvageContainer: boolean; skeleton: string | null; view: string | null; planned?: false; plan?: Readonly<Record<string, unknown>>;",
    "  structured: boolean; structure: boolean; judgeView: OakOpenUIJudgeView; taughtPresets: readonly string[];",
    "}>;",
    `export type OakPendingKind = ${kind};`,
    "",
    `export const OAK_OPENUI_BLOCKS: Readonly<Record<string, OakOpenUIBlock>> = ${JSON.stringify(Object.fromEntries(ordered.map(fragment => [fragment.name, fragment])), null, 2)};`,
    "",
    `export const OAK_PENDING_CAP: Readonly<Record<OakPendingKind, number>> = ${JSON.stringify(Object.fromEntries(pending.map(fragment => [fragment.pendingKind, fragment.pendingCap])))};`,
    "",
  ].join("\n");
}

const writeOrCheck = (target, body, check, command) => {
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch { /* First build. */ }
  if (check) {
    if (current !== body) { console.error(`openui: ${target.replace(root, "")} is stale; run ${command}`); process.exit(1); }
  } else if (current !== body) writeFileSync(target, body);
};

