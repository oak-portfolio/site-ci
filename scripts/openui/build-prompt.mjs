const skipSpace = (text, at) => { while (/\s/.test(text[at] ?? "")) at++; return at; };
function spansOf(text, open) {
  const items = [];
  let depth = 0, quote = false, start = -1, end = -1;
  for (let at = open; at < text.length; at++) {
    const char = text[at];
    if (quote) { if (char === "\\") at++; else if (char === "\"") { quote = false; end = at + 1; } continue; }
    if (char === "\"") { quote = true; if (depth === 1 && start < 0) start = at; continue; }
    if ("[{".includes(char)) { depth++; if (depth === 2 && start < 0) start = at; continue; }
    if ("]}".includes(char)) {
      depth--;
      if (depth === 1) end = at + 1;
      if (depth === 0) { if (start >= 0) items.push({ start, end }); return { close: at, items }; }
      continue;
    }
    if (depth !== 1) continue;
    if (char === ",") { items.push({ start, end }); start = -1; }
    else if (!/\s/.test(char)) { if (start < 0) start = at; end = at + 1; }
  }
  throw new Error("openui: unclosed JSON container");
}
const keyOf = (text, item) => { let at = item.start + 1; while (text[at] !== "\"") at += text[at] === "\\" ? 2 : 1; return JSON.parse(text.slice(item.start, at + 1)); };
const fragmentIds = fragments => fragments.flatMap(fragment => Array.isArray(fragment) ? fragment.map(entry => entry.id) : Object.keys(fragment));

export function oakMergeStrays(text, merge, fragments) {
  const parsed = JSON.parse(text), found = merge.key ? parsed[merge.key] : parsed, ids = new Set(fragmentIds(fragments));
  return (Array.isArray(found) ? found.map(entry => entry.id) : Object.keys(found))
    .filter(id => !ids.has(id)).map(id => `${id} lives only in ${merge.output}; move it to a fragment in ${merge.from}`);
}

export function oakMergeJson(text, merge, fragments) {
  let open = skipSpace(text, 0);
  if (merge.key) {
    const member = spansOf(text, open).items.find(item => keyOf(text, item) === merge.key);
    if (!member) throw new Error(`openui: no "${merge.key}" in the merged file`);
    open = skipSpace(text, text.indexOf(":", member.start + JSON.stringify(merge.key).length) + 1);
  }
  const map = text[open] === "{";
  const entries = fragments.flatMap(fragment => map ? Object.entries(fragment) : fragment.map(entry => [entry.id, entry]));
  const ids = entries.map(([id]) => id);
  const twice = ids.filter((id, index) => typeof id !== "string" || ids.indexOf(id) !== index);
  if (twice.length) throw new Error(`openui: fragments define ${twice.join(", ")} more than once or without an id`);
  const { close, items } = spansOf(text, open);
  if (!entries.length && !items.length) return text;
  const first = items[0], last = items.at(-1);
  const indent = first ? text.slice(text.lastIndexOf("\n", first.start) + 1, first.start) : "  ";
  const sep = items.length > 1 ? text.slice(items.at(-2).end, last.start) : `,\n${indent}`;
  const sample = first ? text.slice(first.start, first.end) : "";
  const unit = sample.includes("\n") ? sample.split("\n")[1].match(/^ */)[0].length - indent.length : 0;
  const show = value => (unit ? JSON.stringify(value, null, unit) : JSON.stringify(value)).split("\n").join(`\n${indent}`);
  const body = entries.map(([id, value]) => map ? `${JSON.stringify(id)}: ${show(value)}` : show(value)).join(sep);
  const head = first ? text.slice(open + 1, first.start) : `\n${indent}`;
  const tail = last ? text.slice(last.end, close) : "\n";
  return `${text.slice(0, open + 1)}${body ? `${head}${body}${tail}` : ""}${text.slice(close)}`;
}

const fragmentsOf = (merge) => existsSync(`${root}${merge.from}`)
  ? readdirSync(`${root}${merge.from}`).filter(file => file.endsWith(merge.suffix ?? ".json")).sort().map(file => JSON.parse(readFileSync(`${root}${merge.from}${file}`, "utf8")))
  : [];

const promptOf = (specJson) => { const spec = JSON.parse(specJson); return generateSystemPrompt({ library: spec, promptOptions: spec.promptOptions }); };

export const OAK_PROMPT_BUDGET = { totalBytes: 16_384, warnBytes: 14_000, componentBytes: 700 };

export function oakPromptBudget(prompt, spec) {
  const bytes = text => Buffer.byteLength(text);
  const names = Object.keys(spec.components);
  const rows = new Map(names.map(name => [name, { name, line: 0, rule: 0, example: 0 }]));
  for (const line of prompt.split("\n")) {
    const row = rows.get(line.match(/^(\w+)\(/)?.[1]);
    if (row) row.line += bytes(line) + 1;
  }
  for (const rule of spec.promptOptions?.additionalRules ?? []) {
    const named = names.filter(name => new RegExp(`\\b${name}\\b`).test(rule));
    for (const name of named) rows.get(name).rule += Math.round(bytes(rule) / named.length);
  }
  for (const line of (spec.promptOptions?.examples ?? []).flatMap(example => example.split("\n"))) {
    const row = rows.get(line.match(/^\w+ = (\w+)\(/)?.[1]);
    if (row) row.example += bytes(line) + 1;
  }
  const table = [...rows.values()].map(row => ({ ...row, total: row.line + row.rule + row.example }));
  const totalBytes = bytes(prompt);
  const problems = [
    ...(totalBytes > OAK_PROMPT_BUDGET.totalBytes ? [`prompt is ${totalBytes} bytes, over the ${OAK_PROMPT_BUDGET.totalBytes} ceiling`] : []),
    ...table.filter(row => row.total > OAK_PROMPT_BUDGET.componentBytes).map(row => `${row.name} is ${row.total} bytes, over the ${OAK_PROMPT_BUDGET.componentBytes} per component`),
  ];
  const warnings = totalBytes > OAK_PROMPT_BUDGET.warnBytes
    ? [`prompt is ${totalBytes} bytes, past ${OAK_PROMPT_BUDGET.warnBytes} bytes: the next teach PR moves rules into componentGroups notes or retires a rule`] : [];
  return { totalBytes, rows: table, problems, warnings };
}

export function oakOpenUIGenerated({ oakRenderLibrary, oakPromptLibrary, promptOptions }) {
  const specOf = library => `${JSON.stringify({ ...library.toSpec(), schema: library.toJSONSchema(), id: oakRenderLibrary.id, promptOptions }, null, 2)}\n`;
  const spec = specOf(oakPromptLibrary);
  return {
    "spec.json": spec,
    "render-spec.json": specOf(oakRenderLibrary),
    "system-prompt.ts": `// Generated by scripts/openui/build-prompt.mjs from spec.json. Do not edit.\nexport const oakOpenUISystemPrompt = ${JSON.stringify(promptOf(spec))};\n`,
  };
}

function main() {
  const check = process.argv.includes("--check");
  const fragments = oakBlockFragments();
  const problems = fragments.flatMap(oakBlockProblems);
  if (problems.length) { console.error(`openui: fragment problems\n${problems.join("\n")}`); process.exit(1); }
  writeOrCheck(`${dir}blocks.generated.ts`, oakBlocksSource(fragments), check, "npm run openui:prompt");
  for (const merge of OAK_MERGES) {
    const text = readFileSync(`${root}${merge.output}`, "utf8"), fragments = fragmentsOf(merge), strays = oakMergeStrays(text, merge, fragments);
    if (strays.length && check) { console.error(`openui: output entries with no fragment\n${strays.join("\n")}`); process.exit(1); }
    for (const stray of strays) console.warn(`openui: dropped ${stray}`);
    writeOrCheck(`${root}${merge.output}`, oakMergeJson(text, merge, fragments), check, "npm run openui:prompt");
  }
  const libraries = loadTsx("src/lib/openui.tsx");
  const generated = oakOpenUIGenerated(libraries);
  for (const [file, body] of Object.entries(generated)) writeOrCheck(`${dir}${file}`, body, check, "npm run openui:prompt");
  const sources = oakFactSources();
  writeOrCheck(`${root}src/data/generated/card-facts.json`, oakCardFactsJson(sources), check, "npm run openui:prompt");
  writeOrCheck(`${root}src/data/generated/record-facts.json`, oakRecordFactsJson(sources), check, "npm run openui:prompt");
  const taught = Object.keys(libraries.oakPromptLibrary.components).length, rendered = Object.keys(libraries.oakRenderLibrary.components).length;
  const prompt = oakPromptBudget(promptOf(generated["spec.json"]), JSON.parse(generated["spec.json"]));
  if (check) {
    console.log(["component\tline\trule\texample\ttotal", ...prompt.rows.map(row => [row.name, row.line, row.rule, row.example, row.total].join("\t"))].join("\n"));
  }
  for (const warning of prompt.warnings) console.warn(`openui: ${warning}`);
  if (prompt.problems.length) { console.error(`openui: prompt budget\n${prompt.problems.join("\n")}`); process.exit(1); }
  console.log(`openui: ${fragments.length} blocks, ${rendered} rendered, ${taught} taught, prompt ${prompt.totalBytes} bytes${check ? " (checked)" : ""}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
