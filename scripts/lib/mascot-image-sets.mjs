export function createMascotImageSets(manifest) {
  return Object.fromEntries(
    Object.values(manifest)
      .filter((entry) => entry.category === "mascot")
      .map((entry) => {
        if (!entry.imageSet?.avif || !entry.imageSet?.webp) {
          throw new Error(`Mascot needs AVIF and WebP sources: ${entry.src}`);
        }
        if (entry.fallbackFormat !== "webp") {
          throw new Error(`Unexpected mascot fallback format: ${entry.fallbackFormat}`);
        }
        return [entry.src, [
          "image-set(",
          `url("${entry.imageSet.avif}") type("image/avif"),`,
          `url("${entry.imageSet.webp}") type("image/webp"),`,
          `url("${entry.src}") type("image/webp")`,
          ")",
        ].join(" ")];
      }),
  );
}

export const compactSpriteWidth = 1024;

function compactVariant(entry, format) {
  return entry.variants?.[format]?.find((variant) => variant.width === compactSpriteWidth);
}

// Smaller sheet for phones and tablets. Only sprites generated with a 1024 step get one.
export function createCompactMascotImageSets(manifest) {
  return Object.fromEntries(
    Object.values(manifest)
      .filter((entry) => entry.category === "mascot" && compactVariant(entry, "avif") && compactVariant(entry, "webp"))
      .map((entry) => [entry.src, [
        "image-set(",
        `url("${compactVariant(entry, "avif").src}") type("image/avif"),`,
        `url("${compactVariant(entry, "webp").src}") type("image/webp"),`,
        `url("${entry.src}") type("image/webp")`,
        ")",
      ].join(" ")]),
  );
}

export function renderMascotImageSets(manifest) {
  return `// Generated by scripts/generate-responsive-images.mjs. Do not edit by hand.
const mascotImageSets: Record<string, string> = ${JSON.stringify(createMascotImageSets(manifest), null, 2)};
const compactMascotImageSets: Record<string, string> = ${JSON.stringify(createCompactMascotImageSets(manifest), null, 2)};

export function getMascotImageSet(src: string): string {
  return mascotImageSets[src] ?? \`url("\${src}")\`;
}

export function getCompactMascotImageSet(src: string): string {
  return compactMascotImageSets[src] ?? getMascotImageSet(src);
}
`;
}
